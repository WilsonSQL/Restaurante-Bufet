-- ======== 03_CRUD/12_Pagos/CRUD_Pagos_pg.sql ========
--# Permite pagos parciales / mixtos; la venta pasa a Pagada cuando lo pagado iguala el total.
--# La función es atómica: si falla una validación, se revierte todo. FOR UPDATE bloquea la venta mientras se paga.
CREATE OR REPLACE FUNCTION sp_RegistrarPago(
    p_idVenta INT, p_idMetodoPago INT, p_monto NUMERIC, p_referenciaPago VARCHAR DEFAULT NULL)
RETURNS TABLE (idPago INT, saldoPendiente NUMERIC, estadoVenta TEXT, mensaje TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
DECLARE
    v_estado VARCHAR;
    v_total NUMERIC;
    v_pagado NUMERIC;
    v_saldo NUMERIC;
    v_idPago INT;
BEGIN
    SELECT v.estado INTO v_estado FROM Ventas v WHERE v.idVenta = p_idVenta FOR UPDATE;

    IF v_estado IS NULL THEN
        RAISE EXCEPTION 'La venta indicada no existe.';
    END IF;
    IF v_estado <> 'Pendiente' THEN
        RAISE EXCEPTION 'Solo se pueden registrar pagos en ventas Pendientes.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM MetodosPago mp WHERE mp.idMetodoPago = p_idMetodoPago AND mp.estado) THEN
        RAISE EXCEPTION 'El método de pago indicado no existe o está inactivo.';
    END IF;
    IF p_monto IS NULL OR p_monto <= 0 THEN
        RAISE EXCEPTION 'El monto del pago debe ser mayor que cero.';
    END IF;

    SELECT COALESCE(SUM(dv.cantidad * dv.precioUnitario - dv.descuento), 0) INTO v_total
    FROM DetalleVentas dv WHERE dv.idVenta = p_idVenta;

    SELECT COALESCE(SUM(pg.monto), 0) INTO v_pagado
    FROM Pagos pg WHERE pg.idVenta = p_idVenta AND pg.estado = 'Aplicado';

    IF v_total = 0 THEN
        RAISE EXCEPTION 'La venta no tiene productos; no se puede registrar un pago.';
    END IF;
    IF p_monto > v_total - v_pagado THEN
        RAISE EXCEPTION 'El monto excede el saldo pendiente de la venta.';
    END IF;

    INSERT INTO Pagos (idVenta, idMetodoPago, monto, referenciaPago)
    VALUES (p_idVenta, p_idMetodoPago, p_monto, NULLIF(BTRIM(p_referenciaPago), ''))
    RETURNING Pagos.idPago INTO v_idPago;

    v_saldo := v_total - v_pagado - p_monto;

    IF v_saldo = 0 THEN
        UPDATE Ventas SET estado = 'Pagada' WHERE Ventas.idVenta = p_idVenta;
    END IF;

    RETURN QUERY SELECT v_idPago, v_saldo,
                        (CASE WHEN v_saldo = 0 THEN 'Pagada' ELSE 'Pendiente' END)::TEXT,
                        'Pago registrado correctamente.'::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION sp_ConsultarPagosVenta(p_idVenta INT)
RETURNS TABLE (idPago INT, idMetodoPago INT, nombreMetodo VARCHAR, monto NUMERIC,
               fechaPago TIMESTAMP, referenciaPago VARCHAR, estado VARCHAR)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
BEGIN
    IF NOT EXISTS (SELECT 1 FROM Ventas v WHERE v.idVenta = p_idVenta) THEN
        RAISE EXCEPTION 'La venta indicada no existe.';
    END IF;

    RETURN QUERY
    SELECT pg.idPago, pg.idMetodoPago, mp.nombreMetodo, pg.monto, pg.fechaPago, pg.referenciaPago, pg.estado
    FROM Pagos pg
    INNER JOIN MetodosPago mp ON mp.idMetodoPago = pg.idMetodoPago
    WHERE pg.idVenta = p_idVenta
    ORDER BY pg.idPago;
END;
$$;

-- ======== 04_Vistas/Vistas_pg.sql ========
--# Vistas de RestauranteDB. Todas son de solo lectura y se apoyan en las tablas, sin duplicar datos.

--# Ventas con cliente, empleado, total, pagado y saldo
CREATE OR REPLACE VIEW vw_VentasResumen AS
SELECT v.idVenta, v.fechaVenta, v.tipoVenta, v.estado,
       COALESCE(c.nombre || ' ' || c.apellido, 'Cliente casual') AS cliente,
       e.nombre || ' ' || e.apellido AS empleado,
       COALESCE(d.total, 0) AS total,
       COALESCE(p.pagado, 0) AS pagado,
       CASE WHEN v.estado = 'Anulada' THEN 0
            ELSE COALESCE(d.total, 0) - COALESCE(p.pagado, 0) END AS saldo
FROM Ventas v
LEFT JOIN Clientes c ON c.idCliente = v.idCliente
INNER JOIN Empleados e ON e.idEmpleado = v.idEmpleado
LEFT JOIN LATERAL (SELECT SUM(dv.cantidad * dv.precioUnitario - dv.descuento) AS total
                   FROM DetalleVentas dv WHERE dv.idVenta = v.idVenta) d ON TRUE
LEFT JOIN LATERAL (SELECT SUM(pg.monto) AS pagado
                   FROM Pagos pg WHERE pg.idVenta = v.idVenta AND pg.estado = 'Aplicado') p ON TRUE;

--# Menú: productos activos de categorías activas
CREATE OR REPLACE VIEW vw_MenuActivo AS
SELECT p.idProducto, p.nombreProducto, p.descripcion, p.precioVenta, c.nombreCategoria AS categoria
FROM Productos p
INNER JOIN CategoriasProductos c ON c.idCategoria = p.idCategoria
WHERE p.estado AND c.estado
ORDER BY c.nombreCategoria, p.nombreProducto;

--# Mesas con su estado y la próxima reservación (Pendiente o Confirmada)
CREATE OR REPLACE VIEW vw_EstadoMesas AS
SELECT m.idMesa, m.numeroMesa, m.capacidad, m.ubicacion, m.estado,
       r.fechaReservacion AS proximaFecha,
       r.horaReservacion AS proximaHora,
       cl.nombre || ' ' || cl.apellido AS proximaReservaPara
FROM Mesas m
LEFT JOIN LATERAL (SELECT rr.fechaReservacion, rr.horaReservacion, rr.idCliente
                   FROM Reservaciones rr
                   WHERE rr.idMesa = m.idMesa
                     AND rr.estado IN ('Pendiente', 'Confirmada')
                     AND (rr.fechaReservacion + rr.horaReservacion) >= (NOW() AT TIME ZONE 'America/Managua')
                   ORDER BY rr.fechaReservacion, rr.horaReservacion
                   LIMIT 1) r ON TRUE
LEFT JOIN Clientes cl ON cl.idCliente = r.idCliente
ORDER BY m.numeroMesa;

--# Reservaciones del día (hora de Nicaragua)
CREATE OR REPLACE VIEW vw_ReservacionesHoy AS
SELECT r.idReservacion, r.horaReservacion, m.numeroMesa,
       c.nombre || ' ' || c.apellido AS cliente, c.telefono,
       r.cantidadPersonas, r.estado, r.observaciones
FROM Reservaciones r
INNER JOIN Clientes c ON c.idCliente = r.idCliente
INNER JOIN Mesas m ON m.idMesa = r.idMesa
WHERE r.fechaReservacion = (NOW() AT TIME ZONE 'America/Managua')::DATE
ORDER BY r.horaReservacion;

--# Cierre de caja: lo cobrado por día y por método de pago (solo pagos aplicados)
CREATE OR REPLACE VIEW vw_CierreCaja AS
SELECT p.fechaPago::DATE AS fecha, mp.nombreMetodo AS metodoPago,
       COUNT(*) AS cantidadPagos, SUM(p.monto) AS totalCobrado
FROM Pagos p
INNER JOIN MetodosPago mp ON mp.idMetodoPago = p.idMetodoPago
WHERE p.estado = 'Aplicado'
GROUP BY p.fechaPago::DATE, mp.nombreMetodo
ORDER BY fecha DESC, metodoPago;

--# Productos más vendidos (solo ventas pagadas)
CREATE OR REPLACE VIEW vw_ProductosMasVendidos AS
SELECT pr.idProducto, pr.nombreProducto,
       SUM(dv.cantidad) AS unidadesVendidas,
       SUM(dv.cantidad * dv.precioUnitario - dv.descuento) AS ingresos
FROM DetalleVentas dv
INNER JOIN Ventas v ON v.idVenta = dv.idVenta
INNER JOIN Productos pr ON pr.idProducto = dv.idProducto
WHERE v.estado = 'Pagada'
GROUP BY pr.idProducto, pr.nombreProducto
ORDER BY unidadesVendidas DESC, pr.nombreProducto;

--# Existencias por ingrediente y almacén
CREATE OR REPLACE VIEW vw_InventarioActual AS
SELECT i.idIngrediente, i.nombreIngrediente, a.nombreAlmacen AS almacen,
       inv.cantidadDisponible, u.abreviatura AS unidad, i.stockMinimo
FROM Inventario inv
INNER JOIN Ingredientes i ON i.idIngrediente = inv.idIngrediente
INNER JOIN Almacenes a ON a.idAlmacen = inv.idAlmacen
INNER JOIN UnidadesMedida u ON u.idUnidad = i.idUnidad
ORDER BY i.nombreIngrediente, a.nombreAlmacen;

--# Ingredientes cuyo stock total está por debajo del mínimo
CREATE OR REPLACE VIEW vw_StockBajo AS
SELECT i.idIngrediente, i.nombreIngrediente, u.abreviatura AS unidad, i.stockMinimo,
       COALESCE(SUM(inv.cantidadDisponible), 0) AS stockActual,
       i.stockMinimo - COALESCE(SUM(inv.cantidadDisponible), 0) AS faltante
FROM Ingredientes i
INNER JOIN UnidadesMedida u ON u.idUnidad = i.idUnidad
LEFT JOIN Inventario inv ON inv.idIngrediente = i.idIngrediente
WHERE i.estado
GROUP BY i.idIngrediente, i.nombreIngrediente, u.abreviatura, i.stockMinimo
HAVING COALESCE(SUM(inv.cantidadDisponible), 0) < i.stockMinimo
ORDER BY faltante DESC;

--# Lotes con existencia que vencen en los próximos 7 días o ya vencieron (diasRestantes negativo)
CREATE OR REPLACE VIEW vw_LotesPorVencer AS
SELECT l.idLote, l.numeroLote, i.nombreIngrediente, a.nombreAlmacen AS almacen,
       l.cantidadDisponible, l.fechaVencimiento,
       l.fechaVencimiento - (NOW() AT TIME ZONE 'America/Managua')::DATE AS diasRestantes
FROM LotesInventario l
INNER JOIN Ingredientes i ON i.idIngrediente = l.idIngrediente
INNER JOIN Almacenes a ON a.idAlmacen = l.idAlmacen
WHERE l.cantidadDisponible > 0
  AND l.fechaVencimiento IS NOT NULL
  AND l.fechaVencimiento <= (NOW() AT TIME ZONE 'America/Managua')::DATE + 7
ORDER BY l.fechaVencimiento;

