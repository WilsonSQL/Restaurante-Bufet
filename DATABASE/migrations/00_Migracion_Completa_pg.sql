CREATE OR REPLACE FUNCTION sp_InsertarCargo(p_nombreCargo VARCHAR, p_descripcion VARCHAR DEFAULT NULL)
RETURNS TABLE (idCargo INT, mensaje TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
DECLARE v_id INT;
BEGIN
    IF p_nombreCargo IS NULL OR BTRIM(p_nombreCargo) = '' THEN
        RAISE EXCEPTION 'El nombre del cargo es obligatorio.';
    END IF;
    IF EXISTS (SELECT 1 FROM Cargos t WHERE t.nombreCargo = BTRIM(p_nombreCargo)) THEN
        RAISE EXCEPTION 'Ya existe un cargo con ese nombre.';
    END IF;

    INSERT INTO Cargos (nombreCargo, descripcion)
    VALUES (BTRIM(p_nombreCargo), NULLIF(BTRIM(p_descripcion), ''))
    RETURNING Cargos.idCargo INTO v_id;

    RETURN QUERY SELECT v_id, 'Cargo registrado correctamente.'::TEXT;
