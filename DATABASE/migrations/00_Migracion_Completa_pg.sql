-- ======== 01_Tablas/01_TablasRestaurante_pg.sql ========
-- RestauranteDB en PostgreSQL (Supabase). Ejecutar en el SQL Editor; no se crea la base, Supabase ya trae la suya.
-- Los nombres no llevan comillas, por lo que PostgreSQL los guarda en minúsculas (idCliente = idcliente).

/* ---------- 1. Clientes ---------- */
CREATE TABLE Clientes (
    idCliente     INT GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR(80)  NOT NULL,
    apellido      VARCHAR(80)  NOT NULL,
    telefono      VARCHAR(20)  NULL,
    correo        VARCHAR(120) NULL,
    direccion     VARCHAR(250) NULL,
    fechaRegistro TIMESTAMP     NOT NULL DEFAULT (NOW() AT TIME ZONE 'America/Managua'),
    estado        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Clientes PRIMARY KEY (idCliente)
);

/* ---------- 2. Cargos ---------- */
CREATE TABLE Cargos (
    idCargo     INT GENERATED BY DEFAULT AS IDENTITY,
    nombreCargo VARCHAR(80)  NOT NULL,
    descripcion VARCHAR(250) NULL,
    estado      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Cargos PRIMARY KEY (idCargo),
    CONSTRAINT UQ_Cargos_nombreCargo UNIQUE (nombreCargo)
);

/* ---------- 3. Empleados ---------- */
CREATE TABLE Empleados (
    idEmpleado        INT GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR(80)  NOT NULL,
    apellido          VARCHAR(80)  NOT NULL,
    telefono          VARCHAR(20)  NULL,
    direccion         VARCHAR(250) NULL,
    fechaContratacion DATE          NOT NULL,
    salario           NUMERIC(10,2) NOT NULL,
    idCargo           INT           NOT NULL,
    estado            BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Empleados PRIMARY KEY (idEmpleado),
    CONSTRAINT FK_Empleados_Cargos FOREIGN KEY (idCargo) REFERENCES Cargos (idCargo),
    CONSTRAINT CK_Empleados_salario CHECK (salario >= 0)
);

/* ---------- 4. Usuarios ---------- */
CREATE TABLE Usuarios (
    idUsuario      INT GENERATED BY DEFAULT AS IDENTITY,
    nombreUsuario  VARCHAR(50)  NOT NULL,
    contrasenaHash VARCHAR(255) NOT NULL,
    idEmpleado     INT           NOT NULL,
    rol            VARCHAR(30)  NOT NULL,
    estado         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Usuarios PRIMARY KEY (idUsuario),
    CONSTRAINT UQ_Usuarios_nombreUsuario UNIQUE (nombreUsuario),
    CONSTRAINT UQ_Usuarios_idEmpleado UNIQUE (idEmpleado),
    CONSTRAINT FK_Usuarios_Empleados FOREIGN KEY (idEmpleado) REFERENCES Empleados (idEmpleado),
    CONSTRAINT CK_Usuarios_rol CHECK (rol IN ('Administrador', 'Cajero', 'Mesero', 'Cocinero', 'Bodeguero'))
);

/* ---------- 5. CategoriasProductos ---------- */
CREATE TABLE CategoriasProductos (
    idCategoria     INT GENERATED BY DEFAULT AS IDENTITY,
    nombreCategoria VARCHAR(80)  NOT NULL,
    descripcion     VARCHAR(250) NULL,
    estado          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_CategoriasProductos PRIMARY KEY (idCategoria),
    CONSTRAINT UQ_CategoriasProductos_nombreCategoria UNIQUE (nombreCategoria)
);

/* ---------- 6. Productos ---------- */
CREATE TABLE Productos (
    idProducto     INT GENERATED BY DEFAULT AS IDENTITY,
    nombreProducto VARCHAR(120) NOT NULL,
    descripcion    VARCHAR(250) NULL,
    precioVenta    NUMERIC(10,2) NOT NULL,
    idCategoria    INT           NOT NULL,
    estado         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Productos PRIMARY KEY (idProducto),
    CONSTRAINT UQ_Productos_nombreProducto UNIQUE (nombreProducto),
    CONSTRAINT FK_Productos_CategoriasProductos FOREIGN KEY (idCategoria) REFERENCES CategoriasProductos (idCategoria),
    CONSTRAINT CK_Productos_precioVenta CHECK (precioVenta >= 0)
);

/* ---------- 7. UnidadesMedida ---------- */
CREATE TABLE UnidadesMedida (
    idUnidad     INT GENERATED BY DEFAULT AS IDENTITY,
    nombreUnidad VARCHAR(50) NOT NULL,
    abreviatura  VARCHAR(10) NOT NULL,
    CONSTRAINT PK_UnidadesMedida PRIMARY KEY (idUnidad),
    CONSTRAINT UQ_UnidadesMedida_nombreUnidad UNIQUE (nombreUnidad),
    CONSTRAINT UQ_UnidadesMedida_abreviatura UNIQUE (abreviatura)
);

/* ---------- 8. CategoriasIngredientes ---------- */
CREATE TABLE CategoriasIngredientes (
    idCategoriaIngrediente INT GENERATED BY DEFAULT AS IDENTITY,
    nombreCategoria        VARCHAR(80)  NOT NULL,
    descripcion            VARCHAR(250) NULL,
    estado                 BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_CategoriasIngredientes PRIMARY KEY (idCategoriaIngrediente),
    CONSTRAINT UQ_CategoriasIngredientes_nombreCategoria UNIQUE (nombreCategoria)
);

/* ---------- 9. Ingredientes ---------- */
CREATE TABLE Ingredientes (
    idIngrediente          INT GENERATED BY DEFAULT AS IDENTITY,
    nombreIngrediente      VARCHAR(120) NOT NULL,
    descripcion            VARCHAR(250) NULL,
    idCategoriaIngrediente INT           NOT NULL,
    idUnidad               INT           NOT NULL,
    stockMinimo            NUMERIC(12,3) NOT NULL DEFAULT 0,
    estado                 BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Ingredientes PRIMARY KEY (idIngrediente),
    CONSTRAINT UQ_Ingredientes_nombreIngrediente UNIQUE (nombreIngrediente),
    CONSTRAINT FK_Ingredientes_CategoriasIngredientes FOREIGN KEY (idCategoriaIngrediente) REFERENCES CategoriasIngredientes (idCategoriaIngrediente),
    CONSTRAINT FK_Ingredientes_UnidadesMedida FOREIGN KEY (idUnidad) REFERENCES UnidadesMedida (idUnidad),
    CONSTRAINT CK_Ingredientes_stockMinimo CHECK (stockMinimo >= 0)
);

/* ---------- 10. Almacenes ---------- */
CREATE TABLE Almacenes (
    idAlmacen     INT GENERATED BY DEFAULT AS IDENTITY,
    nombreAlmacen VARCHAR(80)  NOT NULL,
    ubicacion     VARCHAR(150) NULL,
    descripcion   VARCHAR(250) NULL,
    estado        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Almacenes PRIMARY KEY (idAlmacen),
    CONSTRAINT UQ_Almacenes_nombreAlmacen UNIQUE (nombreAlmacen)
);

/* ---------- 11. Inventario ---------- */
CREATE TABLE Inventario (
    idInventario        INT GENERATED BY DEFAULT AS IDENTITY,
    idIngrediente       INT           NOT NULL,
    idAlmacen           INT           NOT NULL,
    cantidadDisponible  NUMERIC(12,3) NOT NULL DEFAULT 0,
    fechaActualizacion  TIMESTAMP     NOT NULL DEFAULT (NOW() AT TIME ZONE 'America/Managua'),
    CONSTRAINT PK_Inventario PRIMARY KEY (idInventario),
    CONSTRAINT UQ_Inventario_Ingrediente_Almacen UNIQUE (idIngrediente, idAlmacen),
    CONSTRAINT FK_Inventario_Ingredientes FOREIGN KEY (idIngrediente) REFERENCES Ingredientes (idIngrediente),
    CONSTRAINT FK_Inventario_Almacenes FOREIGN KEY (idAlmacen) REFERENCES Almacenes (idAlmacen),
    CONSTRAINT CK_Inventario_cantidadDisponible CHECK (cantidadDisponible >= 0)
);

/* ---------- 12. Proveedores ---------- */
CREATE TABLE Proveedores (
    idProveedor          INT GENERATED BY DEFAULT AS IDENTITY,
    nombreProveedor      VARCHAR(150) NOT NULL,
    telefono             VARCHAR(20)  NULL,
    correo               VARCHAR(120) NULL,
    direccion            VARCHAR(250) NULL,
    identificacionFiscal VARCHAR(30)  NOT NULL,  -- >> RUC
    estado               BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Proveedores PRIMARY KEY (idProveedor),
    CONSTRAINT UQ_Proveedores_identificacionFiscal UNIQUE (identificacionFiscal)
);

/* ---------- 13. Compras ---------- */
CREATE TABLE Compras (
    idCompra      INT GENERATED BY DEFAULT AS IDENTITY,
    idProveedor   INT           NOT NULL,
    idEmpleado    INT           NOT NULL,
    fechaCompra   DATE          NOT NULL,
    numeroFactura VARCHAR(50)  NOT NULL,
    estado        VARCHAR(20)  NOT NULL DEFAULT 'Pendiente',
    observaciones VARCHAR(250) NULL,
    CONSTRAINT PK_Compras PRIMARY KEY (idCompra),
    CONSTRAINT UQ_Compras_Proveedor_Factura UNIQUE (idProveedor, numeroFactura),
    CONSTRAINT FK_Compras_Proveedores FOREIGN KEY (idProveedor) REFERENCES Proveedores (idProveedor),
    CONSTRAINT FK_Compras_Empleados FOREIGN KEY (idEmpleado) REFERENCES Empleados (idEmpleado),
    CONSTRAINT CK_Compras_estado CHECK (estado IN ('Pendiente', 'Recibida', 'Anulada'))
);

/* ---------- 14. DetalleCompras ---------- */
CREATE TABLE DetalleCompras (
    idDetalleCompra INT GENERATED BY DEFAULT AS IDENTITY,
    idCompra        INT           NOT NULL,
    idIngrediente   INT           NOT NULL,
    cantidad        NUMERIC(12,3) NOT NULL,
    costoUnitario   NUMERIC(10,2) NOT NULL,
    CONSTRAINT PK_DetalleCompras PRIMARY KEY (idDetalleCompra),
    CONSTRAINT UQ_DetalleCompras_Compra_Ingrediente UNIQUE (idCompra, idIngrediente),
    CONSTRAINT FK_DetalleCompras_Compras FOREIGN KEY (idCompra) REFERENCES Compras (idCompra),
    CONSTRAINT FK_DetalleCompras_Ingredientes FOREIGN KEY (idIngrediente) REFERENCES Ingredientes (idIngrediente),
    CONSTRAINT CK_DetalleCompras_cantidad CHECK (cantidad > 0),
    CONSTRAINT CK_DetalleCompras_costoUnitario CHECK (costoUnitario >= 0)
);

/* ---------- 15. MovimientosInventario ---------- */
CREATE TABLE MovimientosInventario (
    idMovimiento    INT GENERATED BY DEFAULT AS IDENTITY,
    idIngrediente   INT           NOT NULL,
    idAlmacen       INT           NOT NULL,
    idEmpleado      INT           NOT NULL,
    tipoMovimiento  VARCHAR(20)  NOT NULL,
    cantidad        NUMERIC(12,3) NOT NULL,
    fechaMovimiento TIMESTAMP     NOT NULL DEFAULT (NOW() AT TIME ZONE 'America/Managua'),
    motivo          VARCHAR(150) NOT NULL,
    observaciones   VARCHAR(250) NULL,
    CONSTRAINT PK_MovimientosInventario PRIMARY KEY (idMovimiento),
    CONSTRAINT FK_MovimientosInventario_Ingredientes FOREIGN KEY (idIngrediente) REFERENCES Ingredientes (idIngrediente),
    CONSTRAINT FK_MovimientosInventario_Almacenes FOREIGN KEY (idAlmacen) REFERENCES Almacenes (idAlmacen),
    CONSTRAINT FK_MovimientosInventario_Empleados FOREIGN KEY (idEmpleado) REFERENCES Empleados (idEmpleado),
    -- >> La cantidad siempre es positiva; el tipo indica si suma o resta.
    CONSTRAINT CK_MovimientosInventario_tipo CHECK (tipoMovimiento IN ('Entrada', 'Salida', 'AjusteEntrada', 'AjusteSalida')),
    CONSTRAINT CK_MovimientosInventario_cantidad CHECK (cantidad > 0)
);

/* ---------- 16. Recetas ---------- */
CREATE TABLE Recetas (
    idReceta      INT GENERATED BY DEFAULT AS IDENTITY,
    idProducto    INT            NOT NULL,
    nombreReceta  VARCHAR(120)  NOT NULL,
    instrucciones TEXT  NULL,
    rendimiento   NUMERIC(10,2)  NOT NULL DEFAULT 1,  -- >> porciones que produce
    estado        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_Recetas PRIMARY KEY (idReceta),
    CONSTRAINT FK_Recetas_Productos FOREIGN KEY (idProducto) REFERENCES Productos (idProducto),
    CONSTRAINT CK_Recetas_rendimiento CHECK (rendimiento > 0)
);

/* ---------- 17. DetalleRecetas ---------- */
CREATE TABLE DetalleRecetas (
    idDetalleReceta  INT GENERATED BY DEFAULT AS IDENTITY,
    idReceta         INT           NOT NULL,
    idIngrediente    INT           NOT NULL,
    cantidadNecesaria NUMERIC(12,3) NOT NULL,
    CONSTRAINT PK_DetalleRecetas PRIMARY KEY (idDetalleReceta),
    CONSTRAINT UQ_DetalleRecetas_Receta_Ingrediente UNIQUE (idReceta, idIngrediente),
    CONSTRAINT FK_DetalleRecetas_Recetas FOREIGN KEY (idReceta) REFERENCES Recetas (idReceta),
    CONSTRAINT FK_DetalleRecetas_Ingredientes FOREIGN KEY (idIngrediente) REFERENCES Ingredientes (idIngrediente),
    CONSTRAINT CK_DetalleRecetas_cantidadNecesaria CHECK (cantidadNecesaria > 0)
);

/* ---------- 18. Ventas ---------- */
CREATE TABLE Ventas (
    idVenta       INT GENERATED BY DEFAULT AS IDENTITY,
    fechaVenta    TIMESTAMP     NOT NULL DEFAULT (NOW() AT TIME ZONE 'America/Managua'),
    idCliente     INT           NULL,  -- >> NULL = cliente casual
    idEmpleado    INT           NOT NULL,
    tipoVenta     VARCHAR(20)  NOT NULL,
    estado        VARCHAR(20)  NOT NULL DEFAULT 'Pendiente',
    observaciones VARCHAR(250) NULL,
    CONSTRAINT PK_Ventas PRIMARY KEY (idVenta),
    CONSTRAINT FK_Ventas_Clientes FOREIGN KEY (idCliente) REFERENCES Clientes (idCliente),
    CONSTRAINT FK_Ventas_Empleados FOREIGN KEY (idEmpleado) REFERENCES Empleados (idEmpleado),
    CONSTRAINT CK_Ventas_tipoVenta CHECK (tipoVenta IN ('Local', 'Llevar', 'Domicilio')),
    CONSTRAINT CK_Ventas_estado CHECK (estado IN ('Pendiente', 'Pagada', 'Anulada'))
);

/* ---------- 19. DetalleVentas ---------- */
CREATE TABLE DetalleVentas (
    idDetalleVenta INT GENERATED BY DEFAULT AS IDENTITY,
    idVenta        INT           NOT NULL,
    idProducto     INT           NOT NULL,
    cantidad       INT           NOT NULL,
    precioUnitario NUMERIC(10,2) NOT NULL,  -- >> precio vigente al momento de la venta
    descuento      NUMERIC(10,2) NOT NULL DEFAULT 0,  -- >> monto en C$, no porcentaje
    CONSTRAINT PK_DetalleVentas PRIMARY KEY (idDetalleVenta),
    CONSTRAINT UQ_DetalleVentas_Venta_Producto UNIQUE (idVenta, idProducto),
    CONSTRAINT FK_DetalleVentas_Ventas FOREIGN KEY (idVenta) REFERENCES Ventas (idVenta),
    CONSTRAINT FK_DetalleVentas_Productos FOREIGN KEY (idProducto) REFERENCES Productos (idProducto),
    CONSTRAINT CK_DetalleVentas_cantidad CHECK (cantidad > 0),
    CONSTRAINT CK_DetalleVentas_precioUnitario CHECK (precioUnitario >= 0),
    CONSTRAINT CK_DetalleVentas_descuento CHECK (descuento >= 0 AND descuento <= cantidad * precioUnitario)
);

/* ---------- 20. MetodosPago ---------- */
CREATE TABLE MetodosPago (
    idMetodoPago INT GENERATED BY DEFAULT AS IDENTITY,
    nombreMetodo VARCHAR(50)  NOT NULL,
    descripcion  VARCHAR(250) NULL,
    estado       BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_MetodosPago PRIMARY KEY (idMetodoPago),
    CONSTRAINT UQ_MetodosPago_nombreMetodo UNIQUE (nombreMetodo)
);

/* ---------- 21. Pagos ---------- */
CREATE TABLE Pagos (
    idPago         INT GENERATED BY DEFAULT AS IDENTITY,
    idVenta        INT           NOT NULL,
    idMetodoPago   INT           NOT NULL,
    monto          NUMERIC(10,2) NOT NULL,
    fechaPago      TIMESTAMP     NOT NULL DEFAULT (NOW() AT TIME ZONE 'America/Managua'),
    referenciaPago VARCHAR(80)  NULL,  -- >> Nº de transacción o voucher (tarjeta/transferencia)
    estado         VARCHAR(20)  NOT NULL DEFAULT 'Aplicado',
    CONSTRAINT PK_Pagos PRIMARY KEY (idPago),
    CONSTRAINT FK_Pagos_Ventas FOREIGN KEY (idVenta) REFERENCES Ventas (idVenta),
    CONSTRAINT FK_Pagos_MetodosPago FOREIGN KEY (idMetodoPago) REFERENCES MetodosPago (idMetodoPago),
    CONSTRAINT CK_Pagos_monto CHECK (monto > 0),
    CONSTRAINT CK_Pagos_estado CHECK (estado IN ('Aplicado', 'Anulado'))
);

/* ---------- 22. Mesas ---------- */
CREATE TABLE Mesas (
    idMesa     INT GENERATED BY DEFAULT AS IDENTITY,
    numeroMesa INT           NOT NULL,
    capacidad  INT           NOT NULL,
    ubicacion  VARCHAR(100) NULL,
    estado     VARCHAR(20)  NOT NULL DEFAULT 'Disponible',
    CONSTRAINT PK_Mesas PRIMARY KEY (idMesa),
    CONSTRAINT UQ_Mesas_numeroMesa UNIQUE (numeroMesa),
    CONSTRAINT CK_Mesas_numeroMesa CHECK (numeroMesa > 0),
    CONSTRAINT CK_Mesas_capacidad CHECK (capacidad BETWEEN 1 AND 50),
    CONSTRAINT CK_Mesas_estado CHECK (estado IN ('Disponible', 'Ocupada', 'Reservada', 'Mantenimiento'))
);

/* ---------- 23. Reservaciones ---------- */
CREATE TABLE Reservaciones (
    idReservacion    INT GENERATED BY DEFAULT AS IDENTITY,
    idCliente        INT           NOT NULL,
    idMesa           INT           NOT NULL,
    fechaReservacion DATE          NOT NULL,
    horaReservacion  TIME(0)       NOT NULL,
    cantidadPersonas INT           NOT NULL,
    estado           VARCHAR(20)  NOT NULL DEFAULT 'Pendiente',
    observaciones    VARCHAR(250) NULL,
    CONSTRAINT PK_Reservaciones PRIMARY KEY (idReservacion),
    CONSTRAINT FK_Reservaciones_Clientes FOREIGN KEY (idCliente) REFERENCES Clientes (idCliente),
    CONSTRAINT FK_Reservaciones_Mesas FOREIGN KEY (idMesa) REFERENCES Mesas (idMesa),
    CONSTRAINT CK_Reservaciones_cantidadPersonas CHECK (cantidadPersonas > 0),
    CONSTRAINT CK_Reservaciones_estado CHECK (estado IN ('Pendiente', 'Confirmada', 'Cancelada', 'Completada'))
);

/* ---------- 24. Mermas ---------- */
CREATE TABLE Mermas (
    idMerma       INT GENERATED BY DEFAULT AS IDENTITY,
    idIngrediente INT           NOT NULL,
    idAlmacen     INT           NOT NULL,
    idEmpleado    INT           NOT NULL,
    cantidad      NUMERIC(12,3) NOT NULL,
    fechaMerma    TIMESTAMP     NOT NULL DEFAULT (NOW() AT TIME ZONE 'America/Managua'),
    motivo        VARCHAR(150) NOT NULL,
    observaciones VARCHAR(250) NULL,
    CONSTRAINT PK_Mermas PRIMARY KEY (idMerma),
    CONSTRAINT FK_Mermas_Ingredientes FOREIGN KEY (idIngrediente) REFERENCES Ingredientes (idIngrediente),
    CONSTRAINT FK_Mermas_Almacenes FOREIGN KEY (idAlmacen) REFERENCES Almacenes (idAlmacen),
    CONSTRAINT FK_Mermas_Empleados FOREIGN KEY (idEmpleado) REFERENCES Empleados (idEmpleado),
    CONSTRAINT CK_Mermas_cantidad CHECK (cantidad > 0)
);

/* ---------- 25. LotesInventario ---------- */
CREATE TABLE LotesInventario (
    idLote             INT GENERATED BY DEFAULT AS IDENTITY,
    idIngrediente      INT           NOT NULL,
    idCompra           INT           NULL,  -- >> NULL = lote sin compra asociada (donación, producción propia)
    numeroLote         VARCHAR(50)  NOT NULL,
    fechaIngreso       DATE          NOT NULL,
    fechaVencimiento   DATE          NULL,  -- >> NULL = no perecedero
    cantidadInicial    NUMERIC(12,3) NOT NULL,
    cantidadDisponible NUMERIC(12,3) NOT NULL,
    idAlmacen          INT           NOT NULL,
    CONSTRAINT PK_LotesInventario PRIMARY KEY (idLote),
    CONSTRAINT UQ_LotesInventario_Ingrediente_Lote_Almacen UNIQUE (idIngrediente, numeroLote, idAlmacen),
    CONSTRAINT FK_LotesInventario_Ingredientes FOREIGN KEY (idIngrediente) REFERENCES Ingredientes (idIngrediente),
    CONSTRAINT FK_LotesInventario_Compras FOREIGN KEY (idCompra) REFERENCES Compras (idCompra),
    CONSTRAINT FK_LotesInventario_Almacenes FOREIGN KEY (idAlmacen) REFERENCES Almacenes (idAlmacen),
    CONSTRAINT CK_LotesInventario_cantidadInicial CHECK (cantidadInicial > 0),
    CONSTRAINT CK_LotesInventario_cantidadDisponible CHECK (cantidadDisponible >= 0 AND cantidadDisponible <= cantidadInicial),
    CONSTRAINT CK_LotesInventario_fechaVencimiento CHECK (fechaVencimiento IS NULL OR fechaVencimiento >= fechaIngreso)
);

