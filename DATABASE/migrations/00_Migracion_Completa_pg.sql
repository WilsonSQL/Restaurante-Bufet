               WHERE r.idMesa = p_idMesa
                 AND r.fechaReservacion = p_fechaReservacion
                 AND r.estado IN ('Pendiente', 'Confirmada')
                 AND ABS(EXTRACT(EPOCH FROM (r.horaReservacion - p_horaReservacion))) < 7200) THEN
        RAISE EXCEPTION 'La mesa ya tiene una reservación en ese horario (se requieren 2 horas de separación).';
    END IF;

