--# 2. El detalle solo cambia mientras la venta esté Pendiente, y el precio unitario no se modifica
CREATE OR REPLACE FUNCTION trg_fn_detalleventas_integridad() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_idVenta INT;
    v_estado VARCHAR;
BEGIN
    IF TG_OP = 'DELETE' THEN v_idVenta := OLD.idVenta; ELSE v_idVenta := NEW.idVenta; END IF;

    SELECT v.estado INTO v_estado FROM Ventas v WHERE v.idVenta = v_idVenta;

    IF v_estado IS DISTINCT FROM 'Pendiente' THEN
        RAISE EXCEPTION 'No se puede modificar el detalle de una venta que no está Pendiente.';
    END IF;

    IF TG_OP = 'UPDATE' AND NEW.precioUnitario <> OLD.precioUnitario THEN
        RAISE EXCEPTION 'El precio unitario de una línea de venta no se puede modificar.';
    END IF;

    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_detalleventas_integridad ON DetalleVentas;
CREATE TRIGGER trg_detalleventas_integridad
    BEFORE INSERT OR UPDATE OR DELETE ON DetalleVentas
    FOR EACH ROW EXECUTE FUNCTION trg_fn_detalleventas_integridad();

--# 3. Al completar o cancelar una reservación, la mesa vuelve a Disponible si no tiene otra reservación activa ese día
CREATE OR REPLACE FUNCTION trg_fn_reservacion_libera_mesa() RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    UPDATE Mesas m
    SET estado = 'Disponible'
    WHERE m.idMesa = NEW.idMesa
      AND m.estado = 'Reservada'
      AND NOT EXISTS (SELECT 1 FROM Reservaciones r
                      WHERE r.idMesa = NEW.idMesa
                        AND r.idReservacion <> NEW.idReservacion
                        AND r.fechaReservacion = NEW.fechaReservacion
                        AND r.estado IN ('Pendiente', 'Confirmada'));
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_reservacion_libera_mesa ON Reservaciones;
CREATE TRIGGER trg_reservacion_libera_mesa
    AFTER UPDATE OF estado ON Reservaciones
    FOR EACH ROW
    WHEN (NEW.estado IN ('Completada', 'Cancelada') AND OLD.estado IS DISTINCT FROM NEW.estado)
    EXECUTE FUNCTION trg_fn_reservacion_libera_mesa();

--# 4. Siempre debe quedar al menos un administrador activo
CREATE OR REPLACE FUNCTION trg_fn_usuarios_ultimo_admin() RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    IF OLD.rol = 'Administrador' AND OLD.estado
       AND (NOT NEW.estado OR NEW.rol <> 'Administrador')
       AND NOT EXISTS (SELECT 1 FROM Usuarios u
                       WHERE u.idUsuario <> OLD.idUsuario AND u.rol = 'Administrador' AND u.estado) THEN
        RAISE EXCEPTION 'Debe existir al menos un administrador activo.';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_usuarios_ultimo_admin ON Usuarios;
CREATE TRIGGER trg_usuarios_ultimo_admin
    BEFORE UPDATE OF estado, rol ON Usuarios
    FOR EACH ROW EXECUTE FUNCTION trg_fn_usuarios_ultimo_admin();

--# 5. La fecha de actualización del inventario se llena sola
