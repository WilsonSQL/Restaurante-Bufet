CREATE OR REPLACE FUNCTION sp_InsertarCliente(
    p_nombre VARCHAR, p_apellido VARCHAR, p_telefono VARCHAR,
    p_correo VARCHAR DEFAULT NULL, p_direccion VARCHAR DEFAULT NULL)
RETURNS TABLE (idCliente INT, mensaje TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
DECLARE
    v_correo VARCHAR := NULLIF(BTRIM(p_correo), '');
    v_id INT;
BEGIN
    IF p_nombre IS NULL OR BTRIM(p_nombre) = '' THEN
        RAISE EXCEPTION 'El nombre del cliente es obligatorio.';
    END IF;
    IF p_apellido IS NULL OR BTRIM(p_apellido) = '' THEN
        RAISE EXCEPTION 'El apellido del cliente es obligatorio.';
    END IF;
    IF p_telefono IS NULL OR BTRIM(p_telefono) = '' THEN
        RAISE EXCEPTION 'El teléfono del cliente es obligatorio.';
    END IF;
    IF v_correo IS NOT NULL AND v_correo NOT LIKE '%_@_%._%' THEN
        RAISE EXCEPTION 'El formato del correo electrónico no es válido.';
    END IF;
    IF v_correo IS NOT NULL AND EXISTS (SELECT 1 FROM Clientes c WHERE LOWER(c.correo) = LOWER(v_correo)) THEN
        RAISE EXCEPTION 'Ya existe un cliente registrado con ese correo.';
    END IF;

    INSERT INTO Clientes (nombre, apellido, telefono, correo, direccion)
    VALUES (BTRIM(p_nombre), BTRIM(p_apellido), BTRIM(p_telefono), v_correo, NULLIF(BTRIM(p_direccion), ''))
    RETURNING Clientes.idCliente INTO v_id;

    RETURN QUERY SELECT v_id, 'Cliente registrado correctamente.'::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION sp_ConsultarClientes(p_idCliente INT DEFAULT NULL)
RETURNS TABLE (idCliente INT, nombre VARCHAR, apellido VARCHAR, telefono VARCHAR, correo VARCHAR,
               direccion VARCHAR, fechaRegistro TIMESTAMP, estado BOOLEAN)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
BEGIN
    IF p_idCliente IS NOT NULL AND NOT EXISTS (SELECT 1 FROM Clientes c WHERE c.idCliente = p_idCliente) THEN
        RAISE EXCEPTION 'El cliente que intenta consultar no existe.';
    END IF;

    RETURN QUERY
    SELECT c.idCliente, c.nombre, c.apellido, c.telefono, c.correo, c.direccion, c.fechaRegistro, c.estado
    FROM Clientes c
    WHERE p_idCliente IS NULL OR c.idCliente = p_idCliente
    ORDER BY c.idCliente;
END;
$$;

CREATE OR REPLACE FUNCTION sp_ActualizarCliente(
    p_idCliente INT, p_nombre VARCHAR, p_apellido VARCHAR, p_telefono VARCHAR,
    p_correo VARCHAR DEFAULT NULL, p_direccion VARCHAR DEFAULT NULL)
RETURNS TABLE (mensaje TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
DECLARE
    v_correo VARCHAR := NULLIF(BTRIM(p_correo), '');
BEGIN
    IF NOT EXISTS (SELECT 1 FROM Clientes c WHERE c.idCliente = p_idCliente) THEN
        RAISE EXCEPTION 'El cliente que desea actualizar no existe.';
    END IF;
    IF p_nombre IS NULL OR BTRIM(p_nombre) = '' THEN
        RAISE EXCEPTION 'El nombre es obligatorio.';
    END IF;
    IF p_apellido IS NULL OR BTRIM(p_apellido) = '' THEN
        RAISE EXCEPTION 'El apellido es obligatorio.';
    END IF;
    IF p_telefono IS NULL OR BTRIM(p_telefono) = '' THEN
        RAISE EXCEPTION 'El teléfono es obligatorio.';
    END IF;
    IF v_correo IS NOT NULL AND v_correo NOT LIKE '%_@_%._%' THEN
        RAISE EXCEPTION 'El correo electrónico no tiene un formato válido.';
    END IF;
    IF v_correo IS NOT NULL AND EXISTS (SELECT 1 FROM Clientes c
                                        WHERE LOWER(c.correo) = LOWER(v_correo) AND c.idCliente <> p_idCliente) THEN
        RAISE EXCEPTION 'Ese correo ya pertenece a otro cliente.';
    END IF;

    UPDATE Clientes
    SET nombre = BTRIM(p_nombre),
        apellido = BTRIM(p_apellido),
        telefono = BTRIM(p_telefono),
        correo = v_correo,
        direccion = NULLIF(BTRIM(p_direccion), '')
    WHERE Clientes.idCliente = p_idCliente;

    RETURN QUERY SELECT 'Cliente actualizado correctamente.'::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION sp_EliminarCliente(p_idCliente INT)
RETURNS TABLE (mensaje TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
BEGIN
    IF NOT EXISTS (SELECT 1 FROM Clientes c WHERE c.idCliente = p_idCliente) THEN
        RAISE EXCEPTION 'El cliente que desea eliminar no existe.';
    END IF;
    IF EXISTS (SELECT 1 FROM Clientes c WHERE c.idCliente = p_idCliente AND NOT c.estado) THEN
        RAISE EXCEPTION 'El cliente ya se encuentra inactivo.';
    END IF;

    UPDATE Clientes SET estado = FALSE WHERE Clientes.idCliente = p_idCliente;

    RETURN QUERY SELECT 'Cliente desactivado correctamente.'::TEXT;
END;
$$;

