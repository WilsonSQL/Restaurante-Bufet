-- ======== 03_CRUD/11_DetalleVentas/CRUD_DetalleVentas_pg.sql ========
--# El precio se toma de Productos.precioVenta al momento de agregar; el descuento es un monto en C$
CREATE OR REPLACE FUNCTION sp_AgregarDetalleVenta(
    p_idVenta INT, p_idProducto INT, p_cantidad INT, p_descuento NUMERIC DEFAULT 0)
RETURNS TABLE (idDetalleVenta INT, mensaje TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
DECLARE
    v_precio NUMERIC;
    v_descuento NUMERIC := COALESCE(p_descuento, 0);
    v_id INT;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM Ventas v WHERE v.idVenta = p_idVenta) THEN
        RAISE EXCEPTION 'La venta indicada no existe.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM Ventas v WHERE v.idVenta = p_idVenta AND v.estado = 'Pendiente') THEN
        RAISE EXCEPTION 'Solo se pueden agregar productos a ventas Pendientes.';
    END IF;
    IF EXISTS (SELECT 1 FROM Pagos pg WHERE pg.idVenta = p_idVenta AND pg.estado = 'Aplicado') THEN
        RAISE EXCEPTION 'La venta ya tiene pagos registrados y no puede modificarse.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM Productos pr WHERE pr.idProducto = p_idProducto AND pr.estado) THEN
        RAISE EXCEPTION 'El producto indicado no existe o está inactivo.';
    END IF;
    IF EXISTS (SELECT 1 FROM DetalleVentas dv WHERE dv.idVenta = p_idVenta AND dv.idProducto = p_idProducto) THEN
        RAISE EXCEPTION 'El producto ya está en la venta; use sp_ActualizarDetalleVenta para cambiar la cantidad.';
    END IF;
    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        RAISE EXCEPTION 'La cantidad debe ser mayor que cero.';
    END IF;

    SELECT pr.precioVenta INTO v_precio FROM Productos pr WHERE pr.idProducto = p_idProducto;

    IF v_descuento < 0 OR v_descuento > p_cantidad * v_precio THEN
        RAISE EXCEPTION 'El descuento no puede ser negativo ni mayor al subtotal de la línea.';
    END IF;

    INSERT INTO DetalleVentas (idVenta, idProducto, cantidad, precioUnitario, descuento)
    VALUES (p_idVenta, p_idProducto, p_cantidad, v_precio, v_descuento)
    RETURNING DetalleVentas.idDetalleVenta INTO v_id;

    RETURN QUERY SELECT v_id, 'Producto agregado a la venta correctamente.'::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION sp_ConsultarDetalleVenta(p_idVenta INT)
RETURNS TABLE (idDetalleVenta INT, idProducto INT, nombreProducto VARCHAR, cantidad INT,
               precioUnitario NUMERIC, descuento NUMERIC, subtotal NUMERIC)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
BEGIN
    IF NOT EXISTS (SELECT 1 FROM Ventas v WHERE v.idVenta = p_idVenta) THEN
        RAISE EXCEPTION 'La venta indicada no existe.';
    END IF;

    RETURN QUERY
    SELECT dv.idDetalleVenta, dv.idProducto, pr.nombreProducto, dv.cantidad,
           dv.precioUnitario, dv.descuento, dv.cantidad * dv.precioUnitario - dv.descuento
    FROM DetalleVentas dv
    INNER JOIN Productos pr ON pr.idProducto = dv.idProducto
    WHERE dv.idVenta = p_idVenta
    ORDER BY dv.idDetalleVenta;
END;
$$;

CREATE OR REPLACE FUNCTION sp_ActualizarDetalleVenta(
    p_idDetalleVenta INT, p_cantidad INT, p_descuento NUMERIC DEFAULT 0)
RETURNS TABLE (mensaje TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
DECLARE
    v_idVenta INT;
    v_precio NUMERIC;
    v_descuento NUMERIC := COALESCE(p_descuento, 0);
BEGIN
    SELECT dv.idVenta, dv.precioUnitario INTO v_idVenta, v_precio
    FROM DetalleVentas dv WHERE dv.idDetalleVenta = p_idDetalleVenta;

    IF v_idVenta IS NULL THEN
        RAISE EXCEPTION 'El detalle de venta indicado no existe.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM Ventas v WHERE v.idVenta = v_idVenta AND v.estado = 'Pendiente') THEN
        RAISE EXCEPTION 'Solo se pueden modificar ventas Pendientes.';
    END IF;
    IF EXISTS (SELECT 1 FROM Pagos pg WHERE pg.idVenta = v_idVenta AND pg.estado = 'Aplicado') THEN
        RAISE EXCEPTION 'La venta ya tiene pagos registrados y no puede modificarse.';
    END IF;
    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        RAISE EXCEPTION 'La cantidad debe ser mayor que cero.';
    END IF;
    IF v_descuento < 0 OR v_descuento > p_cantidad * v_precio THEN
        RAISE EXCEPTION 'El descuento no puede ser negativo ni mayor al subtotal de la línea.';
    END IF;

    UPDATE DetalleVentas
    SET cantidad = p_cantidad, descuento = v_descuento
    WHERE DetalleVentas.idDetalleVenta = p_idDetalleVenta;

    RETURN QUERY SELECT 'Detalle de venta actualizado correctamente.'::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION sp_EliminarDetalleVenta(p_idDetalleVenta INT)
RETURNS TABLE (mensaje TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
DECLARE v_idVenta INT;
BEGIN
    SELECT dv.idVenta INTO v_idVenta FROM DetalleVentas dv WHERE dv.idDetalleVenta = p_idDetalleVenta;

    IF v_idVenta IS NULL THEN
        RAISE EXCEPTION 'El detalle de venta indicado no existe.';
