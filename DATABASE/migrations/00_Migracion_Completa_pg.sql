CREATE OR REPLACE FUNCTION sp_InsertarReservacion(
    p_idCliente INT, p_idMesa INT, p_fechaReservacion DATE, p_horaReservacion TIME,
    p_cantidadPersonas INT, p_observaciones VARCHAR DEFAULT NULL)
RETURNS TABLE (idReservacion INT, mensaje TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
DECLARE v_id INT;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM Clientes c WHERE c.idCliente = p_idCliente AND c.estado) THEN
        RAISE EXCEPTION 'El cliente indicado no existe o está inactivo.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM Mesas m WHERE m.idMesa = p_idMesa AND m.estado <> 'Mantenimiento') THEN
        RAISE EXCEPTION 'La mesa indicada no existe o está en mantenimiento.';
    END IF;
    IF p_fechaReservacion IS NULL OR p_horaReservacion IS NULL THEN
        RAISE EXCEPTION 'La fecha y la hora de la reservación son obligatorias.';
    END IF;
    IF (p_fechaReservacion + p_horaReservacion) < (NOW() AT TIME ZONE 'America/Managua') THEN
        RAISE EXCEPTION 'La reservación no puede ser en una fecha y hora pasadas.';
    END IF;
    IF p_cantidadPersonas IS NULL OR p_cantidadPersonas <= 0 THEN
