CREATE OR REPLACE FUNCTION sp_ConsultarVentas(
    p_idVenta INT DEFAULT NULL, p_fechaDesde DATE DEFAULT NULL, p_fechaHasta DATE DEFAULT NULL)
RETURNS TABLE (idVenta INT, fechaVenta TIMESTAMP, tipoVenta VARCHAR, estado VARCHAR, idCliente INT, cliente TEXT,
               idEmpleado INT, empleado TEXT, total NUMERIC, pagado NUMERIC, saldo NUMERIC, observaciones VARCHAR)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
#variable_conflict use_column
BEGIN
    IF p_idVenta IS NOT NULL AND NOT EXISTS (SELECT 1 FROM Ventas v WHERE v.idVenta = p_idVenta) THEN
        RAISE EXCEPTION 'La venta que intenta consultar no existe.';
    END IF;

    RETURN QUERY
    SELECT v.idVenta, v.fechaVenta, v.tipoVenta, v.estado,
           v.idCliente, COALESCE(c.nombre || ' ' || c.apellido, 'Cliente casual')::TEXT,
           v.idEmpleado, (e.nombre || ' ' || e.apellido)::TEXT,
           COALESCE(d.total, 0), COALESCE(pg.pagado, 0), COALESCE(d.total, 0) - COALESCE(pg.pagado, 0),
           v.observaciones
    FROM Ventas v
    LEFT JOIN Clientes c ON c.idCliente = v.idCliente
    INNER JOIN Empleados e ON e.idEmpleado = v.idEmpleado
    LEFT JOIN LATERAL (SELECT SUM(dv.cantidad * dv.precioUnitario - dv.descuento) AS total
                       FROM DetalleVentas dv WHERE dv.idVenta = v.idVenta) d ON TRUE
    LEFT JOIN LATERAL (SELECT SUM(p.monto) AS pagado
                       FROM Pagos p WHERE p.idVenta = v.idVenta AND p.estado = 'Aplicado') pg ON TRUE
    WHERE (p_idVenta IS NULL OR v.idVenta = p_idVenta)
      AND (p_fechaDesde IS NULL OR v.fechaVenta >= p_fechaDesde)
      AND (p_fechaHasta IS NULL OR v.fechaVenta < p_fechaHasta + 1)
    ORDER BY v.idVenta DESC;
